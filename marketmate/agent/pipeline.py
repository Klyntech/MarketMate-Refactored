    def _require_authority(self, required_level: int) -> None:
        """Raise PermissionError if current authority is insufficient."""
        if self._authority_level < required_level:
            raise PermissionError(
                f"Authority level {self._authority_level} insufficient "
                f"(requires {required_level})"
            )

    @staticmethod
    def _format_tool_results_raw(tool_results: list) -> str:
        """Format tool results as a readable text when LLM synthesis fails."""
        lines = []
        for tr in tool_results:
            tool_name = tr.get("tool", "unknown")
            status = tr.get("status", "unknown")

            if status == "success":
                result = tr.get("result", {})
                if isinstance(result, dict):
                    formatted = json.dumps(result, default=str, indent=2)
                else:
                    formatted = str(result)
                lines.append(f"**{tool_name}**:\n{formatted}")
            else:
                error = tr.get("error", "Unknown error")
                lines.append(f"**{tool_name}**: Error — {error}")

        return "\n\n".join(lines) if lines else "No results available."

