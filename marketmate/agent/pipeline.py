"""
marketmate.agent.pipeline
──────────────────────────
LangGraph-based agent pipeline for the MATE AI system.

Creates a graph-based workflow that routes queries through different
brains and tools. Falls back to a simple LLM-direct pipeline when
langgraph is not installed.

Pipeline Graph:
    ┌─────────┐     ┌───────┐     ┌───────────────┐     ┌───────────┐
    │ router  │────▶│ brain │────▶│ tool_executor │────▶│ formatter │
    └─────────┘     └───────┘     └───────────────┘     └───────────┘
                         │                                    ▲
                         │        (skip tools)                │
                         └────────────────────────────────────┘

Nodes:
  router        — Classifies the query and routes to the right brain
  brain         — Executes the appropriate brain module
  tool_executor — Executes tool calls if the brain decides tools are needed
  formatter     — Formats the final response for delivery

State keys:
  query         — The original user query (str)
  session_id    — Session identifier for conversation continuity (str)
  context       — Additional context passed by the caller (dict)
  classification — Which brain was selected (str)
  messages      — Accumulated conversation messages (list[dict])
  tool_calls    — Tool calls generated by the brain (list[dict])
  tool_results  — Results from executing tool calls (list[dict])
  response      — The final formatted response (str)
  metadata      — Pipeline execution metadata (dict)

Brains:
  market_data   — Live prices, market summaries, trends
  signal_intel  — Signal stats, active signals, performance
  account       — Balance, equity, drawdown, risk state
  strategy      — SMC concepts, gate pipeline, session schedule
  system        — Health checks, provider status, diagnostics
  state         — Compiled market state, regime, conviction, zones
  general       — Lightweight general intelligence fallback
"""

