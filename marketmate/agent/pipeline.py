# ─── Routing classification prompt ───────────────────────────────────────────

_CLASSIFICATION_PROMPT = """You are a query router for MATE, a trading intelligence system. Classify the following query into exactly ONE of these categories:

- market_data: Questions about live prices, market summaries, trends, volatility, OHLCV data
- signal_intel: Questions about signals, win rate, performance stats, active trades, PnL
- account: Questions about balance, equity, drawdown, risk state, account info
- strategy: Questions about SMC concepts (BOS, CHoCH, FVG, order blocks), strategy parameters, gates, sessions
- system: Questions about system health, providers, diagnostics, uptime, API status
- state: Questions about market state, bias, conviction, regime, zones, liquidity, state transitions
- general: Everything else — general chat, non-trading questions, greetings, off-topic

Query: "{query}"

Respond with ONLY the category name, nothing else."""


