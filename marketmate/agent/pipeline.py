    # ═════════════════════════════════════════════════════════════════════════

    async def _run_simple_pipeline(self, state: dict) -> dict:
        """
        Simple pipeline without LangGraph — runs the same logical steps
        sequentially: classify → brain → tools → format.
        """
        # Step 1: Route
        state = await self._route_query(state)

        # Step 2: Execute brain
        state = await self._execute_brain(state)

        # Step 3: Execute tools if needed
        if self._should_use_tools(state):
            state = await self._execute_tools(state)

        # Step 4: Format response
        state = await self._format_response(state)

        return state

