    def _get_llm_provider(self) -> Any:
        """Get the LLM provider — injected or global fallback."""
        if self._llm_provider is not None:
            return self._llm_provider

        try:
            from marketmate.core.llm import llm_provider
            return llm_provider
        except ImportError:
            return None

    async def _last_resort_llm_call(self, query: str) -> str:
        """
        Last-resort fallback: call the LLM directly with no tools.
        """
        try:
            llm = self._get_llm_provider()
            if llm is not None:
                result = await llm.chat(
                    system_prompt=(
                        "You are MATE, a helpful AI assistant for the "
                        "MarketMate trading platform. Be concise and helpful."
                    ),
                    user_prompt=query,
                    max_tokens=800,
                    temperature=0.5,
                )
                return result.text
        except Exception as exc:
            log.error("agent_last_resort_llm_failed", error=str(exc))

        return (
            "I'm having trouble processing your request right now. "
            "Please try again in a moment."
        )

    async def _synthesize_from_tools(
        self, query: str, tool_results: list
    ) -> str:
        """
        Synthesize a human-readable response from tool results using the LLM.
        """
        results_text = json.dumps(tool_results, default=str, indent=2)

        # Truncate if very large
        if len(results_text) > 8000:
            results_text = results_text[:8000] + "\n... (truncated)"

        prompt = (
            f"Based on the following tool results, provide a concise, "
            f"conversational answer to the user's question.\n\n"
            f"Question: {query}\n\n"
            f"Tool Results:\n{results_text}\n\n"
            f"Provide a clear, helpful response. Do not mention tools "
            f"or internal processes."
        )

        try:
            llm = self._get_llm_provider()
            if llm is not None:
                result = await llm.chat(
                    system_prompt="You are MATE, a trading AI assistant. Be concise and accurate.",
                    user_prompt=prompt,
                    max_tokens=1200,
                    temperature=0.4,
                )
                return result.text
        except Exception as exc:
            log.warning("agent_synthesis_failed", error=str(exc))

        # Fallback: format raw results
        return self._format_tool_results_raw(tool_results)

